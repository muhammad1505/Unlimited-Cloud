// --- App version -------------------------------------------------------------------
// One source of truth for every surface: the APK, the desktop package, the About
// card, TDLib's application_version and the post-update changelog gate. The value
// lives in gradle.properties; scripts/check-versions.py verifies it still matches
// the newest CHANGELOG.md entry before CI builds a release.
val appVersionName = providers.gradleProperty("unlimitedcloud.versionName").orNull ?: "1.0.0"
require(appVersionName.matches(Regex("\\d+\\.\\d+\\.\\d+"))) {
    "unlimitedcloud.versionName '$appVersionName' must be MAJOR.MINOR.PATCH"
}
val appVersionCode = appVersionName.split('.').map { it.toInt() }.let { (major, minor, patch) ->
    major * 10_000 + minor * 100 + patch
}

// --- Telegram credentials injection ------------------------------------------------
// Real credentials never live in the repository. They come from a Gradle property,
// an environment variable, or the ignored local.properties file; CI falls back to
// dummy values so the project still compiles without secrets.
fun localProperty(key: String): String? {
    val file = rootProject.file("local.properties")
    if (!file.exists()) return null
    return Properties().apply {
        file.inputStream().use { load(it) }
    }.getProperty(key)
}

val telegramApiId = providers.gradleProperty("TELEGRAM_API_ID").orNull
    ?: providers.environmentVariable("TELEGRAM_API_ID").orNull
    ?: localProperty("TELEGRAM_API_ID")
    ?: "0"

val telegramApiHash = providers.gradleProperty("TELEGRAM_API_HASH").orNull
    ?: providers.environmentVariable("TELEGRAM_API_HASH").orNull
    ?: localProperty("TELEGRAM_API_HASH")
    ?: "00000000000000000000000000000000"

val generatedTelegramDir = layout.buildDirectory.dir("generated/telegram/commonMain/kotlin")

val generateTelegramCredentials = tasks.register("generateTelegramCredentials") {
    val outputDir = generatedTelegramDir
    val apiId = telegramApiId
    val apiHash = telegramApiHash
    inputs.property("apiId", apiId)
    // Only a digest is tracked so the secret never shows up in build scans.
    inputs.property("apiHashDigest", apiHash.hashCode())
    outputs.dir(outputDir)

    doLast {
        val target = outputDir.get().file("com/unlimitedcloud/config/TelegramCredentials.kt").asFile
        target.parentFile.mkdirs()
        target.writeText(
            """
            |// Generated by :composeApp:generateTelegramCredentials. Do not edit or commit.
            |package com.unlimitedcloud.config
            |
            |internal object TelegramCredentials {
            |    const val API_ID: Int = $apiId
            |    const val API_HASH: String = "$apiHash"
            |}
            |""".trimMargin(),
        )
    }
}

// --- Generated version info --------------------------------------------------------
// Exposing the version as Kotlin source keeps the UI free of hardcoded strings and
// lets the changelog dialog compare the installed versionCode with the last one the
// user acknowledged.
val generatedVersionDir = layout.buildDirectory.dir("generated/version/commonMain/kotlin")

val generateAppBuildInfo = tasks.register("generateAppBuildInfo") {
    val outputDir = generatedVersionDir
    val versionName = appVersionName
    val versionCode = appVersionCode
    inputs.property("versionName", versionName)
    inputs.property("versionCode", versionCode)
    outputs.dir(outputDir)

    doLast {
        val target = outputDir.get().file("com/unlimitedcloud/AppBuildInfo.kt").asFile
        target.parentFile.mkdirs()
        target.writeText(
            """
            |// Generated by :composeApp:generateAppBuildInfo. Do not edit or commit.
            |package com.unlimitedcloud
            |
            |internal object AppBuildInfo {
            |    const val VERSION_NAME: String = "$versionName"
            |    const val VERSION_CODE: Int = $versionCode
            |}
            |""".trimMargin(),
        )
    }
}

// --- Changelog bundling ------------------------------------------------------------
// CHANGELOG.md is the only place a release is described: the same file feeds the
// in-app changelog screen, the post-update dialog and GitHub release notes.
val changelogSource = rootProject.file("CHANGELOG.md")
val generatedChangelogDir = layout.buildDirectory.dir("generated/changelog/commonMain/kotlin")

// Escapes one markdown line into a Kotlin string literal. Quote and dollar are
// handled through char codes so this build script stays readable in a plain diff
// without nested escapes.
fun String.asKotlinLiteral(): String = buildString {
    for (char in this@asKotlinLiteral) {
        when (char) {
            '\\' -> append("\\\\")
            34.toChar() -> append("\\\"")
            36.toChar() -> append('\\').append('$')
            '\n' -> append("\\n")
            '\r' -> append("\\r")
            else -> append(char)
        }
    }
}

val generateChangelog = tasks.register("generateChangelog") {
    val outputDir = generatedChangelogDir
    val source = changelogSource
    inputs.file(source)
    outputs.dir(outputDir)

    doLast {
        val lines = if (source.exists()) source.readLines() else emptyList()
        val rendered = lines.joinToString(separator = ",\n") { line ->
            "        \"${line.asKotlinLiteral()}\""
        }
        val target = outputDir.get().file("com/unlimitedcloud/changelog/ChangelogData.kt").asFile
        target.parentFile.mkdirs()
        target.writeText(
            buildString {
                appendLine("// Generated from CHANGELOG.md by :composeApp:generateChangelog. Do not edit.")
                appendLine("package com.unlimitedcloud.changelog")
                appendLine()
                appendLine("internal val CHANGELOG_MARKDOWN_LINES: List<String> = listOf(")
                appendLine(rendered)
                appendLine(")")
            },
        )
    }
}

tasks.withType<KotlinCompilationTask<*>>().configureEach {
    dependsOn(generateTelegramCredentials, generateAppBuildInfo, generateChangelog)
}

// Shared UI + domain code is published as an Android library and a desktop JVM
// application. AGP 9 refuses to combine com.android.application with the Kotlin
// Multiplatform plugin, so the APK shell lives in the :androidApp module.
kotlin {
    jvmToolchain(17)

    android {
        // The public API package stays com.unlimitedcloud; the Android namespace only
        // drives R/BuildConfig and must differ from the :androidApp module namespace.
        namespace = "com.unlimitedcloud.shared"
        compileSdk = libs.versions.androidCompileSdk.get().toInt()
        minSdk = libs.versions.androidMinSdk.get().toInt()
    }

    jvm("desktop")

    sourceSets {
        commonMain.dependencies {
            implementation(libs.compose.runtime)
            implementation(libs.compose.foundation)
            implementation(libs.compose.material3)
            implementation(libs.compose.ui)
            implementation(libs.compose.animation)

            implementation(libs.kotlinx.coroutines.core)
            implementation(libs.kotlinx.serialization.json)

            implementation(libs.koin.core)
            implementation(libs.koin.compose)

            implementation(libs.sqldelight.runtime)
            implementation(libs.sqldelight.coroutines)

            implementation(libs.okio)
            implementation(libs.filekit.dialogs.compose)
        }

        androidMain.dependencies {
            implementation(libs.androidx.activity.compose)
            // FileProvider for the share sheet and the persisted SAF grant helper.
            implementation(libs.androidx.core)
            // JNA drives the same libtdjson JSON API on Android; the AAR variant
            // carries the dispatch libraries for every Android ABI.
            implementation("net.java.dev.jna:jna:${libs.versions.jna.get()}@aar")
            implementation(libs.koin.android)
            implementation(libs.sqldelight.android.driver)
            // Periodic gallery sync while the app is closed.
            implementation(libs.androidx.work.runtime.ktx)
        }

        getByName("desktopMain").dependencies {
            implementation(compose.desktop.currentOs)
            implementation(libs.kotlinx.coroutines.swing)
            implementation(libs.sqldelight.sqlite.driver)

            // TDLib's JSON C API is reached through JNA from java.library.path or a
            // libtdjson resource on the classpath. tdlight only publishes the JNI
            // wrapper (tdjni) for desktop, never tdjson, so the deb/rpm/msi are
            // packaged without natives and the user supplies libtdjson/.dll.
            implementation(libs.jna)

            // The JDK mixer only understands WAV/AIFF, so MP3 and FLAC are
            // decoded to PCM by these pure-Java libraries before playback.
            implementation(libs.jlayer)
            implementation(libs.jflac)
        }
    }
}

